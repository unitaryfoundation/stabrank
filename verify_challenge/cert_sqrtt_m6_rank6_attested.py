"""Certificate (attested): chi(|sqrtT>^{ot 6}) >= 7, and >= 7 for 7 <= m <= 10 by
projection, from the complete list of six-term stabilizer decompositions of
|sqrtT>^{ot 5}.

Setting. |sqrtT> = (|0> + zeta|1>)/sqrt 2, zeta = exp(i pi/8), t_m = (1, zeta)^{ot m}
the unnormalized target, V4 the span of its four conjugates under
Gal(Q(zeta)/Q(i)), which lies in the span of every stabilizer decomposition
(cert_sqrtt_galois.py), and chi(t_5) = 6 exactly (cert_sqrtt_galois_census.py
and the six product states spanning Sym^5).

Why a six-term decomposition of t_6 is a lift. Both computational slices of
t_6 along qubit 0 are t_5 up to a scalar (<0| gives t_5, <1| gives zeta t_5),
and a computational slice of a stabilizer state is a stabilizer state or zero.
Since chi(t_5) = 6, neither slice of any term vanishes, so each term is
|0> u_j + |1> b_j with u_j, b_j nonzero stabilizer states, which forces qubit 0
to be maximally mixed in the term and b_j = omega_j P_j u_j with P_j a Pauli
and omega_j a fourth root of unity. Then {u_j} with the coefficients c_j and
{omega_j P_j u_j} with the coefficients c_j / zeta... more precisely
sum_j (c_j omega_j / zeta) (P_j u_j) = t_5, are two six-term decompositions of
t_5 (the second is written on the canonical forms of the P_j u_j, whose phases
are absorbed into omega_j). Given the complete list of six-term decompositions
of t_5 with their exact coefficients, the lift is a dictionary search: for each
decomposition U and each term u_j, every Pauli image of u_j is looked up in the
list's term index, and a decomposition V receives a vote for slot j when its
coefficient at that image equals c_j omega / zeta for a fourth root of unity
omega; a V voted in all six slots by six distinct images is rebuilt as a
six-qubit decomposition and decided exactly. No candidate survives, so
chi(t_6) >= 7.

Why the list is complete (the attested part). Six terms with span containing
V4 and no smaller decomposition are independent, so their residues modulo V4
span a plane; pivoting on one term a, the other five residues are pairwise
parallel or zero modulo V4 + span(a). The runner research/sqrtt_m5_rank6/
census.py keys every five-qubit stabilizer state by the projective class of
its residue modulo V4 + span(a), exactly modulo the primes 2013265921 and
1811939329 (zeta mapped to a primitive sixteenth root of unity, a ring
homomorphism on Z[zeta]; parallel residues over Q(zeta) have equal keys mod P
unless one vanishes mod P, so every exact decomposition lands in one class
together with the zero set Z_a), and records every class C with |C u Z_a| >= 6
whose members have rank at least 6 mod P as a candidate set. (A 6 x 6 minor of
a matrix with entries in {0, +-1, +-i} has norm at most 6^6 = 46,656 < P, so
exact rank at least 6 implies rank at least 6 modulo either prime, and this
screen discards no class that could carry a decomposition.) Pivots run over
the 8,585 orbit representatives of the states under the group G generated by
the qubit permutations and the diagonal Clifford S^{ot 5}; G maps the set of
decompositions to itself (permutations fix t_5 and V4; the automorphism
zeta -> zeta^13 fixes every stabilizer state and sends sum c_j s_j = t_1 to
sum sigma(c_j) s_j = t_13 = S^{+ ot 5} t_1), so every decomposition is
G-equivalent to one containing a representative. The 859 stored block outputs
(research/sqrtt_m5_rank6/results/, hashed in batch_manifest.json) list, per
representative, Z_a, the class-size histogram and the candidate sets: one
candidate set in all, the 18 permutation-symmetric five-qubit stabilizer
states. Every six-term decomposition of t_5 is therefore an independent
six-subset of those 18 states: 3,375 of them, in 852 orbits under G.

What this script does under the budget. (1) Re-enumerates the 2,423,520
five-qubit stabilizer states exactly, checks the count, their distinctness,
and the SHA-256 of the array against the manifest, so the stored indices refer
to this dictionary. (2) Reads every stored block (the verifier has already
checked each file's hash), checks that the blocks are contiguous and no pivot
lies in V4, and checks that the orbits under G of the stored pivots are
pairwise disjoint and cover all N states, which is the coverage the
completeness argument needs. (3) Chooses `recomputed` blocks from the seed it
prints, re-runs their pivot censuses from scratch and compares the canonical
block text byte for byte with the stored output. (4) Re-decides the candidate
set exactly: its rank over Q(zeta_16), that V4 lies in its span, the
independent six-subsets by exact 6 x 6 minors on a set of coordinates on
which the span projects injectively, and the exact coefficients of every
decomposition. (5) Closes the list under G (any image not already listed is
added with exact coefficients). (6) Runs the lift in full over the orbit
representatives of the list, with coefficient matching on the reductions of
the exact coefficients modulo both primes and an exact decision of every
candidate. The claim is printed only if every step passes; a surviving lift
candidate would be a six-term decomposition of |sqrtT>^6 and the script then
exits 1 after printing it.

Printed claims: CERTIFIED chi(qubit_sqrtT^6) >= 7
                CERTIFIED chi(qubit_sqrtT^7) >= 7   (projection monotonicity, and likewise)
                CERTIFIED chi(qubit_sqrtT^8) >= 7
                CERTIFIED chi(qubit_sqrtT^9) >= 7
                CERTIFIED chi(qubit_sqrtT^10) >= 7
"""

