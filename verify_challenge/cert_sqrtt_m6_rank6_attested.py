def say(msg):
    print(f"[{time.time() - T0:6.1f}s] {msg}", flush=True)


def fail(msg):
    print(msg, file=sys.stderr)
    raise SystemExit(1)


def gauss_rows(codes_sel):
    """rows of Gaussian integers (re, im) for exact 6 x 6 minors."""
    tab = {0: (0, 0), 1: (1, 0), 2: (0, 1), 3: (-1, 0), 4: (0, -1)}
    return [[tab[int(c)] for c in row] for row in codes_sel]


def gdet(Mx):
    """determinant of a square matrix of Gaussian integers, fraction-free (Bareiss) over Z[i]."""
    n = len(Mx)
    A = [[complex(a, b) for (a, b) in row] for row in Mx]
    # exact integer arithmetic through Python ints on (re, im) pairs
    A = [[(int(a.real), int(a.imag)) for a in row] for row in A]

    def mul(x, y):
        return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])

    def sub(x, y):
        return (x[0] - y[0], x[1] - y[1])

    def div(x, y):          # exact division in Z[i]
        n2 = y[0] * y[0] + y[1] * y[1]
        re = x[0] * y[0] + x[1] * y[1]
        im = x[1] * y[0] - x[0] * y[1]
        assert re % n2 == 0 and im % n2 == 0
        return (re // n2, im // n2)

    sign = 1
    prev = (1, 0)
    for k in range(n - 1):
        if A[k][k] == (0, 0):
            sw = next((r for r in range(k + 1, n) if A[r][k] != (0, 0)), None)
            if sw is None:
                return (0, 0)
            A[k], A[sw] = A[sw], A[k]
            sign = -sign
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                A[i][j] = div(sub(mul(A[i][j], A[k][k]), mul(A[i][k], A[k][j])), prev)
        prev = A[k][k]
    d = A[n - 1][n - 1]
    return d if sign == 1 else (-d[0], -d[1])


def anp_mod(e, g, P):
    """reduction of an element of Q(zeta_16) (ANP in the generator zeta) modulo P with zeta -> g."""
    coeffs = e.to_list()                      # highest degree first
    deg = len(coeffs) - 1
    val = 0
    for i, c in enumerate(coeffs):
        num, den = int(c.numerator), int(c.denominator)
        if den % P == 0:
            fail("a coefficient's denominator vanishes mod P")
        val = (val + num * pow(den, P - 2, P) * pow(g, deg - i, P)) % P
    return val


def exact_coeffs_K(codes_sel, m):
    """exact coefficients in K = Q(zeta_16) (as ANP elements) with sum c_j s_j = t_1, or None."""
    K = field_K()
    xz = K.from_sympy(ZETA)
    tab = [K.zero, K.one, xz ** 4, -K.one, -(xz ** 4)]
    rows = [[tab[int(c)] for c in row] for row in codes_sel]
    A = DomainMatrix(rows, (len(rows), 1 << m), K).transpose()
    b = DomainMatrix([[xz ** int(ww)] for ww in weights(m)], (1 << m, 1), K)
    _, piv = A.transpose().rref()
    if len(piv) != len(rows):
        return None
    Al = A.to_list()
    bl = b.to_list()
    x = DomainMatrix([Al[i] for i in piv], (len(piv), len(rows)), K).lu_solve(
        DomainMatrix([bl[i] for i in piv], (len(piv), 1), K))
    if (A * x - b).to_Matrix() != sp.zeros(1 << m, 1):
        return None
    return [x[j, 0].element for j in range(len(rows))]


def main():
    print(f"seed: {CERT_SEED}")
    K = field_K()
    z = K.from_sympy(ZETA)
    V = DomainMatrix([[z ** (k * w) for k in CONJ] for w in range(4)], (4, 4), K)
    if V.det() == K.zero:
        fail("the Vandermonde minor is singular")
    say("Galois: the four conjugates of t_m are independent for m >= 3 (exact Vandermonde)")

    # (1) the dictionary
    codes = stabilizer_codes(M)
    N, D = codes.shape
    if N != count_states(M):
        fail(f"enumerated {N} states, formula gives {count_states(M)}")
    H = hash_rows(codes)
    if len(np.unique(H, axis=0)) != N:
        fail("two enumerated states coincide")
    sha = hashlib.sha256(codes.tobytes()).hexdigest()
    man = json.load(open(MANIFEST))
    if sha != man["codes_sha256"]:
        fail(f"dictionary hash {sha[:16]} differs from the manifest's {man['codes_sha256'][:16]}")
    say(f"{N} five-qubit stabilizer states enumerated, distinct, SHA-256 matches the manifest")
    # index lookup by the first hash word (checked unique)
    h1 = H[:, 0]
    order = np.argsort(h1, kind="stable")
    h1s = h1[order]
    if (h1s[1:] == h1s[:-1]).any():
        fail("first hash word not unique; lookup would be ambiguous")

    def index_of(rows_codes):
        hh = hash_rows(rows_codes)[:, 0]
        pos = np.searchsorted(h1s, hh)
        if (pos >= N).any() or (h1s[np.minimum(pos, N - 1)] != hh).any():
            fail("an image state is not in the dictionary")
        return order[pos]

    # (2) the stored blocks
    batches = man["batches"]
    if len(batches) != man["blocks"]:
        fail("manifest block count mismatch")
    pivots = []
    cand_sets = {}
    stored = {}
    for b in batches:
        path = os.path.join(ROOT, b["output"])
        txt = open(path).read()
        stored[b["id"]] = txt
        rec = json.loads(txt)
        if rec["codes_sha256"] != sha or rec["m"] != M:
            fail(f"block {b['id']}: dictionary hash or m mismatch")
        if [r["pivot"] for r in rec["results"]] != rec["pivots"]:
            fail(f"block {b['id']}: results do not match its pivot list")
        for r in rec["results"]:
            if r.get("in_V4"):
                fail(f"pivot {r['pivot']} lies in V4 (impossible at m = 5)")
            pivots.append(int(r["pivot"]))
            for c in r["candidates"]:
                cand_sets.setdefault(tuple(c["members"]), []).append(int(r["pivot"]))
    ids = sorted(int(b["id"].split("_")[1]) for b in batches)
    if ids != list(range(len(batches))):
        fail("block ids are not contiguous")
    if len(set(pivots)) != len(pivots) or len(pivots) != man["representatives"]:
        fail("stored pivots are not distinct or do not match the manifest count")
    say(f"{len(batches)} blocks, {len(pivots)} stored pivots, {sum(len(v) for v in cand_sets.values())} candidate "
        f"records over {len(cand_sets)} distinct candidate sets")

    # (2b) orbit coverage of the stored pivots under G = S_5 x <S^(x)5>
    maps = perm_index_maps(M)
    w = weights(M)
    piv_arr = np.array(pivots, dtype=np.int64)
    covered = np.zeros(N, dtype=np.int64)
    for a in piv_arr:
        base = codes[a][np.array(maps)]                        # (120, D)
        imgs = []
        for s in range(4):
            imgs.append(np.where(base != 0, ((base - 1 + s * w[None, :]) % 4) + 1, 0).astype(np.int8))
        img = canon_codes(np.concatenate(imgs))
        idx = np.unique(index_of(img))
        covered[idx] += 1
    if (covered == 0).any():
        fail(f"{int((covered == 0).sum())} states lie in no stored pivot's orbit")
    if (covered > 1).any():
        fail("two stored pivots share an orbit")
    say("the orbits of the stored pivots under G are disjoint and cover every state: one representative per orbit")

    # (3) re-run `recomputed` blocks from scratch
    att_k = 2
    rng = random.Random(CERT_SEED)
    chosen = sorted(rng.sample(range(len(batches)), att_k))
    fields = [Field(M, P, SEED + 1000 * i) for i, P in enumerate(PRIMES)]
    R = [F.residues(codes) for F in fields]
    census.G.update(N=N, codes=codes, fields=fields, R=R, out=None, m=M, codes_sha=sha)
    for bid in chosen:
        b = batches[bid]
        rec = json.loads(stored[b["id"]])
        res = [pivot_census(int(a)) for a in rec["pivots"]]
        txt = block_record(rec["block"], M, rec["pivots"], res, sha)
        if txt != stored[b["id"]]:
            fail(f"re-run of block {b['id']} differs from the stored output")
        say(f"block {b['id']} re-run from scratch ({len(rec['pivots'])} pivots): identical to the stored output")
    del R
    census.G.clear()

    # (4) exact decisions on the candidate sets
    conj_rows = [[ZETA ** int(k * ww) for ww in w] for k in CONJ]
    xz = z
    tabK = [K.zero, K.one, xz ** 4, -K.one, -(xz ** 4)]
    decs = {}
    for mem in cand_sets:
        sel = np.array(mem)
        rows = [[tabK[int(c)] for c in row] for row in codes[sel]]
        Sm = DomainMatrix(rows, (len(rows), D), K)
        rk = Sm.rank()
        if rk < 6:
            say(f"  candidate set of {len(mem)}: exact rank {rk} < 6, carries no decomposition")
            continue
        ext = DomainMatrix(rows + [[K.from_sympy(e) for e in r] for r in conj_rows], (len(rows) + 4, D), K)
        if rk == 6 and ext.rank() == 6:
            # independent six-subsets by exact minors on coordinates where the span projects injectively
            _, pivcols = Sm.rref()
            if len(pivcols) != 6:
                fail("rref pivot count differs from the rank")
            G6 = gauss_rows(codes[sel][:, list(pivcols)])
            n6 = 0
            for sub in itertools.combinations(range(len(mem)), 6):
                if gdet([G6[i] for i in sub]) != (0, 0):
                    decs[tuple(int(i) for i in sel[list(sub)])] = None
                    n6 += 1
            say(f"  candidate set of {len(mem)}: exact rank 6 with V4 inside its span; {n6} independent "
                f"six-subsets, each a decomposition")
        else:
            n6 = 0
            for sub in itertools.combinations(range(len(mem)), 6):
                key = tuple(int(i) for i in sel[list(sub)])
                if exact_coeffs_K(codes[list(key)], M) is not None:
                    decs[key] = None
                    n6 += 1
            say(f"  candidate set of {len(mem)}: exact rank {rk}; {n6} six-subsets decided exactly as decompositions")
    say(f"six-term decompositions of t_5 from the stored candidate sets: {len(decs)}")
    for key in decs:
        cs = exact_coeffs_K(codes[list(key)], M)
        if cs is None:
            fail(f"subset {key} is not an exact decomposition")
        decs[key] = cs
    say("exact coefficients of every decomposition computed in Q(zeta_16)")

    # (5) closure under G
    involved = sorted({i for k in decs for i in k})
    inv_pos = {s: j for j, s in enumerate(involved)}
    sub = codes[involved]
    images = []
    for idx in maps:
        base = sub[:, idx]
        for s in range(4):
            img = np.where(base != 0, ((base - 1 + s * w[None, :]) % 4) + 1, 0).astype(np.int8)
            images.append(index_of(canon_codes(img)))
    full = dict(decs)
    orbit_rep = {}
    new = 0
    for k in list(decs):
        if k in orbit_rep:
            continue
        pos = [inv_pos[i] for i in k]
        orb = {tuple(sorted(int(ids[p]) for p in pos)) for ids in images}
        for im in orb:
            orbit_rep.setdefault(im, k)
            if im not in full:
                cs = exact_coeffs_K(codes[list(im)], M)
                if cs is None:
                    fail(f"group image {im} is not a decomposition")
                full[im] = cs
                new += 1
    reps = sorted({orbit_rep[k] for k in full})
    say(f"closure under G: {len(full)} decompositions ({new} added by the closure), {len(reps)} orbits")

    # (6) the lift to six copies
    gs = [root16(P) for P in PRIMES]
    cm = {k: [[anp_mod(c, gs[fi], PRIMES[fi]) for c in v] for fi in range(2)] for k, v in full.items()}
    byterm = {}
    for k in full:
        for j, t in enumerate(k):
            byterm.setdefault(t, []).append((k, j))
    zinv = [pow(gs[fi], PRIMES[fi] - 2, PRIMES[fi]) for fi in range(2)]
    i_pow = [[pow(gs[fi], 4 * e, PRIMES[fi]) for e in range(4)] for fi in range(2)]
    cache = {}
    cands = []
    for U in reps:
        votes = {}
        for j, t in enumerate(U):
            if t not in cache:
                cache[t] = pauli_images_all(codes[t], M)
            for can_bytes in cache[t]:
                v = int(index_of(np.frombuffer(can_bytes, dtype=np.int8)[None, :])[0])
                for (Vk, slot) in byterm.get(v, []):
                    for e in range(4):
                        if all(((cm[U][fi][j] * i_pow[fi][e]) % PRIMES[fi]) * zinv[fi] % PRIMES[fi] == cm[Vk][fi][slot]
                               for fi in range(2)):
                            votes.setdefault(Vk, {}).setdefault(j, set()).add((v, e))
        for Vk, slots in votes.items():
            if len(slots) == 6:
                for choice in itertools.product(*[sorted(slots[j]) for j in range(6)]):
                    vs = [c[0] for c in choice]
                    if sorted(vs) == sorted(Vk):
                        cands.append((U, Vk, [(U[j], vs[j], choice[j][1]) for j in range(6)]))
    say(f"lift over {len(reps)} orbit representatives: {len(cands)} candidates pass the coefficient match")
    found = 0
    for (U, Vk, pairs) in cands:
        rows = []
        for (u, v, e) in pairs:
            cv = codes[v]
            bot = np.where(cv != 0, ((cv - 1 + e) % 4) + 1, 0).astype(np.int8)
            rows.append(canon_codes(np.concatenate([codes[u], bot])[None, :])[0])
        if exact_coeffs_K(np.array(rows), M + 1) is not None:
            found += 1
            print("DECOMPOSITION FOUND: six-term decomposition of |sqrtT>^6 with terms")
            for r in rows:
                print("   ", "".join(".1i-j"[c] for c in r))
    if found:
        fail("a six-term decomposition of |sqrtT>^6 exists; the bound chi >= 7 is false")
    say("no candidate survives the exact decision: no six-term decomposition of |sqrtT>^6")
    say("projection: (<0| (x) I)|sqrtT>^(m+1) is |sqrtT>^m up to a scalar, so chi is monotone in m")
    print("CERTIFIED chi(qubit_sqrtT^6) >= 7")
    r = 7
    for m in range(7, 11):
        print(f"CERTIFIED chi(qubit_sqrtT^{m}) >= {r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
