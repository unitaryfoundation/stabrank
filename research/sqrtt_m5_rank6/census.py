M61 = (1 << 61) - 1


def say(*a):
    print(f"[{time.time()-T0:7.1f}s]", *a, flush=True)


def codes_path(m, out):
    return os.path.join(out, f"codes_m{m}.npy")


def load_codes(m, out):
    p = codes_path(m, out)
    if os.path.exists(p):
        return np.load(p)
    c = stabilizer_codes(m)
    np.save(p, c)
    return c


def hash_dict(codes):
    h = hash_rows(codes)
    return {(int(a), int(b)): i for i, (a, b) in enumerate(h)}, h


# ----------------------------------------------------------------------------- reps
def cmd_reps(m, out):
    os.makedirs(out, exist_ok=True)
    codes = load_codes(m, out)
    N = len(codes)
    say(f"m={m}: {N} states")
    H = hash_rows(codes)
    maps = perm_index_maps(m)
    best = H.copy()
    for (pi, s), img in group_images(codes, m, maps):
        Hi = hash_rows(img)
        better = (Hi[:, 0] < best[:, 0]) | ((Hi[:, 0] == best[:, 0]) & (Hi[:, 1] < best[:, 1]))
        best[better] = Hi[better]
        if pi % 24 == 0 and s == 0:
            say(f"  group element {pi * 4 + s}/{len(maps) * 4}")
    is_rep = (best[:, 0] == H[:, 0]) & (best[:, 1] == H[:, 1])
    reps = np.flatnonzero(is_rep)
    # orbit sizes: count states sharing the orbit's minimal hash
    key = best[:, 0] * 1000003 + best[:, 1]
    _, inv, cnt = np.unique(key, return_inverse=True, return_counts=True)
    sizes = cnt[inv][reps]
    assert sizes.sum() == N, (sizes.sum(), N)
    np.savez(os.path.join(out, f"reps_m{m}.npz"), reps=reps, sizes=sizes)
    say(f"orbit representatives under G (order {len(maps) * 4}): {len(reps)}; sizes sum to N; "
        f"max orbit {sizes.max()}, orbits of size 1: {(sizes == 1).sum()}")


