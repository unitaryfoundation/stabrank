G = {}


def pivot_census(a):
    """candidate sets for the pivot state a: list of (members) with |C u Z_a| >= 6 and rank mod P >= 6."""
    t0 = time.time()
    N = G['N']
    keys = []
    zero_any = np.zeros(N, dtype=bool)
    for fi, F in enumerate(G['fields']):
        R = G['R'][fi]
        P = F.P
        ra = R[a]
        nzr = np.flatnonzero(ra)
        if len(nzr) == 0:
            return {'pivot': int(a), 'in_V4': True, 'candidates': [], 'seconds': time.time() - t0}
        q = int(nzr[0])
        invq = pow(int(ra[q]), P - 2, P)
        k = np.empty((N, 3), dtype=np.int64)
        chunk = 200000
        for s in range(0, N, chunk):
            Rc = R[s:s + chunk]
            lam = (Rc[:, q] * invq) % P
            Rp = (Rc - (lam[:, None] * ra[None, :]) % P) % P
            k[s:s + chunk] = F.keys_of(Rp)
        zero_any |= (k[:, 0] == -1)
        keys.append(k)
    K = np.concatenate(keys, axis=1)
    Za = np.flatnonzero(zero_any)
    nz = np.flatnonzero(~zero_any)
    # hash the six key columns to two 61-bit words, then sort
    rng = np.random.default_rng(SEED + 99)
    hk = np.zeros((len(nz), 2), dtype=np.int64)
    for h in range(2):
        c = rng.integers(1, M61, size=6, dtype=np.int64)
        acc = np.zeros(len(nz), dtype=np.int64)
        for j in range(6):
            acc = (acc + ((K[nz, j] % M61) * c[j]) % M61) % M61
        hk[:, h] = acc
    order = np.lexsort((hk[:, 1], hk[:, 0]))
    hs = hk[order]
    brk = np.flatnonzero((hs[1:, 0] != hs[:-1, 0]) | (hs[1:, 1] != hs[:-1, 1])) + 1
    starts = np.concatenate([[0], brk]); ends = np.concatenate([brk, [len(hs)]])
    sizes = ends - starts
    need = max(6 - len(Za), 1)
    cands = []
    nbig = 0
    for b in np.flatnonzero(sizes >= need):
        members = nz[order[starts[b]:ends[b]]]
        sel = np.concatenate([members, Za])
        nbig += 1
        rk = 0
        for F in G['fields']:
            rk = max(rk, rank_mod(F.values(G['codes'][sel]).tolist(), F.P))
        if rk >= 6:
            cands.append({'members': [int(i) for i in np.sort(sel)], 'class_size': int(len(members)), 'rank_mod_p': int(rk)})
    hist = {int(s): int(c) for s, c in enumerate(np.bincount(sizes)) if c}
    return {'pivot': int(a), 'in_V4': False, 'Z_a': [int(i) for i in Za], 'classes': int(len(sizes)), 'class_hist': hist,
            'classes_tested': nbig, 'candidates': cands, 'seconds': time.time() - t0}


def block_record(bid, m, pivots, results, codes_sha):
    """the stored form of a block: timing removed, canonical JSON text (round-tripped so that integer and string
    keys serialize identically), one line."""
    res = []
    for r in results:
        r = {k: v for k, v in r.items() if k != 'seconds'}
        res.append(r)
    rec = {'block': int(bid), 'm': int(m), 'pivots': [int(a) for a in pivots], 'codes_sha256': codes_sha, 'results': res}
    return json.dumps(json.loads(json.dumps(rec)), sort_keys=True, separators=(',', ':')) + '\n'


def run_block(args):
    bid, pivots = args
    res = [pivot_census(int(a)) for a in pivots]
    path = os.path.join(G['out'], 'blocks', f'block_{bid:05d}.json')
    with open(path + '.tmp', 'w') as f:
        json.dump({'block': bid, 'm': G['m'], 'pivots': [int(a) for a in pivots], 'results': res,
                   'codes_sha256': G['codes_sha'], 'seconds': sum(r['seconds'] for r in res)}, f)
    os.replace(path + '.tmp', path)
    return bid, len(pivots), sum(r['seconds'] for r in res), sum(len(r['candidates']) for r in res)


def cmd_run(m, out, workers, pivots_arg, limit, block_size):
    import multiprocessing as mp
    os.makedirs(os.path.join(out, 'blocks'), exist_ok=True)
    codes = load_codes(m, out)
    N = len(codes)
    reps = np.load(os.path.join(out, f"reps_m{m}.npz"))['reps'] if pivots_arg is None else np.array(pivots_arg)
    if limit:
        reps = reps[:limit]
    say(f"m={m}: {N} states, {len(reps)} pivots, {workers} workers")
    fields = [Field(m, P, SEED + 1000 * i) for i, P in enumerate(PRIMES)]
    R = [F.residues(codes) for F in fields]
    say("residues modulo V4 under both primes computed")
    G.update(N=N, codes=codes, fields=fields, R=R, out=out, m=m,
             codes_sha=hashlib.sha256(codes.tobytes()).hexdigest())
    blocks = [(i, reps[s:s + block_size]) for i, s in enumerate(range(0, len(reps), block_size))]
    done = {int(f.split('_')[1].split('.')[0]) for f in os.listdir(os.path.join(out, 'blocks')) if f.endswith('.json')}
    todo = [b for b in blocks if b[0] not in done]
    say(f"{len(blocks)} blocks of {block_size} pivots, {len(todo)} to run")
    ctx = mp.get_context('fork')
    tot_c = 0
    with ctx.Pool(workers) as pool:
        for bid, n, sec, nc in pool.imap_unordered(run_block, todo):
            tot_c += nc
            say(f"  block {bid}: {n} pivots, {sec:.0f} s, {nc} candidate sets (total {tot_c})")
    say("run complete")


# ----------------------------------------------------------------------------- collect
def coeffs_mod(codes_sel, m, F):
    """coefficients c mod P with sum c_j s_j = t_1 (as values mod P), or None if dependent / not spanning."""
    P = F.P
    V = F.values(codes_sel) % P                      # (r, D)
    r, D = V.shape
    w = weights(m)
    t = np.array([pow(F.g, int(ww), P) for ww in w], dtype=np.int64)
    # Gaussian elimination on the augmented transposed system V^T c = t
    A = [[int(V[j, x]) for j in range(r)] + [int(t[x])] for x in range(D)]
    rk = 0; pivcols = []
    for c in range(r):
        piv = next((i for i in range(rk, D) if A[i][c]), None)
        if piv is None:
            return None
        A[rk], A[piv] = A[piv], A[rk]
        inv = pow(A[rk][c], P - 2, P)
        A[rk] = [(x * inv) % P for x in A[rk]]
        for i in range(D):
            if i != rk and A[i][c]:
                f = A[i][c]
                A[i] = [(x - f * y) % P for x, y in zip(A[i], A[rk])]
        rk += 1
    if any(A[i][r] for i in range(rk, D)):
        return None
    return [A[j][r] for j in range(r)]


def cmd_collect(m, out):
    codes = load_codes(m, out)
    N = len(codes)
    fields = [Field(m, P, SEED + 1000 * i) for i, P in enumerate(PRIMES)]
    bl = sorted(f for f in os.listdir(os.path.join(out, 'blocks')) if f.endswith('.json'))
    reps = np.load(os.path.join(out, f"reps_m{m}.npz"))['reps']
    seen_piv = set(); cand = []
    for f in bl:
        d = json.load(open(os.path.join(out, 'blocks', f)))
        for r in d['results']:
            seen_piv.add(r['pivot'])
            for c in r['candidates']:
                cand.append((r['pivot'], tuple(c['members'])))
    missing = set(int(x) for x in reps) - seen_piv
    say(f"{len(bl)} blocks, {len(seen_piv)} pivots done, {len(missing)} representatives missing, {len(cand)} candidate sets")
    if missing:
        say("INCOMPLETE: not every representative has been run")
    # exact decisions per distinct candidate set
    sets = {}
    for piv, mem in cand:
        sets.setdefault(mem, []).append(piv)
    decomps = {}
    for mem, pivs in sets.items():
        sel = np.array(mem)
        rk = exact_rank(codes[sel], m)
        if rk < 6:
            say(f"  candidate set of {len(mem)} (pivots {pivs[:3]}): exact rank {rk} < 6, rejected")
            continue
        # every independent 6-subset is a decomposition; screen by rank mod P then confirm exactly
        n6 = 0
        for sub in itertools.combinations(range(len(mem)), 6):
            idx = sel[list(sub)]
            if all(coeffs_mod(codes[idx], m, F) is not None for F in fields):
                key = tuple(int(i) for i in idx)
                if key not in decomps:
                    cs = exact_coefficients(codes[idx], m)
                    if cs is None:
                        say(f"  WARNING: subset {key} passes mod P but not exactly")
                        continue
                    decomps[key] = {'coeff': [str(c) for c in cs]}
                    n6 += 1
        say(f"  candidate set of {len(mem)} (from {len(pivs)} pivots): exact rank {rk}, {n6} new six-term decompositions")
    say(f"decompositions from representatives: {len(decomps)}")
    # closure under G
    hd, H = hash_dict(codes)
    maps = perm_index_maps(m)
    full = dict(decomps)
    orbit_of = {}
    for key in list(decomps):
        if key in orbit_of:
            continue
        orb = set()
        for pi, idx in enumerate(maps):
            for s in range(4):
                img = tuple(sorted(hd[tuple(int(v) for v in hash_rows(group_image_single(codes[i], m, idx, s)[None, :])[0])] for i in key))
                orb.add(img)
        for img in orb:
            orbit_of[img] = key
            if img not in full:
                cs = exact_coefficients(codes[list(img)], m)
                if cs is None:
                    say(f"  ERROR: group image {img} of {key} is not a decomposition")
                    continue
                full[img] = {'coeff': [str(c) for c in cs]}
    norb = len({orbit_of[k] for k in full})
    say(f"complete list after closure under G: {len(full)} six-term decompositions in {norb} orbits")
    # coefficients mod P for the lift dictionary
    rec = []
    for key, v in full.items():
        rec.append({'terms': list(key), 'coeff': v['coeff'],
                    'coeff_mod': [coeffs_mod(codes[list(key)], m, F) for F in fields]})
    json.dump({'m': m, 'pivots_done': len(seen_piv), 'reps': int(len(reps)), 'complete': not missing,
               'candidate_sets': len(sets), 'decompositions': rec, 'orbits': norb},
              open(os.path.join(out, f'decomps_m{m}.json'), 'w'))
    say("written decomps")


# ----------------------------------------------------------------------------- lift
def pauli_images(code, m):
    """all (canonical code, omega exponent) with X^a Z^b (code) = i^omega * canonical, over a, b in F_2^m."""
    D = 1 << m
    xs = np.arange(D)
    out = {}
    for a in range(D):
        perm = xs ^ a                                    # amplitude at x moves to x ^ a
        base = np.zeros(D, dtype=np.int8)
        base[perm] = code
        for b in range(D):
            ph = 2 * np.array([bin(x & b).count('1') & 1 for x in range(D)], dtype=np.int64)
            img = np.where(base != 0, ((base - 1 + ph) % 4) + 1, 0).astype(np.int8)
            first = int(np.argmax(img != 0))
            e0 = int(img[first]) - 1
            can = canon_codes(img[None, :])[0]
            out.setdefault(can.tobytes(), set()).add(e0)
    return out


def cmd_lift(m, out):
    codes = load_codes(m, out)
    D = 1 << m
    fields = [Field(m, P, SEED + 1000 * i) for i, P in enumerate(PRIMES)]
    dec = json.load(open(os.path.join(out, f'decomps_m{m}.json')))
    if not dec['complete']:
        say("the decomposition list is not complete; the lift is not a proof")
    L = dec['decompositions']
    hd, H = hash_dict(codes)
    byterm = {}
    for di, d in enumerate(L):
        for j, t in enumerate(d['terms']):
            byterm.setdefault(t, []).append((di, j))
    g = [F.g for F in fields]
    zinv = [pow(gg, PRIMES[i] - 2, PRIMES[i]) for i, gg in enumerate(g)]        # 1/zeta mod P
    i_pow = [[pow(gg, 4 * e, PRIMES[i]) for e in range(4)] for i, gg in enumerate(g)]
    lifts = []
    cache = {}
    for di, d in enumerate(L):
        votes = {}                                       # candidate V index -> {slot j: (v index, omega)}
        for j, t in enumerate(d['terms']):
            if t not in cache:
                cache[t] = pauli_images(codes[t], m)
            for can_bytes, e0s in cache[t].items():
                v = hd[tuple(int(x) for x in hash_rows(np.frombuffer(can_bytes, dtype=np.int8)[None, :])[0])]
                for (vi, slot) in byterm.get(v, []):
                    # need coeff_V[slot] == c_j * omega / zeta with omega = i^e, e in e0s + {0,1,2,3} (the free phase c')
                    for e in range(4):
                        ok = True
                        for fi in range(2):
                            P = PRIMES[fi]
                            want = (d['coeff_mod'][fi][j] * i_pow[fi][e] % P) * zinv[fi] % P
                            if want != L[vi]['coeff_mod'][fi][slot]:
                                ok = False; break
                        if ok:
                            votes.setdefault(vi, {}).setdefault(j, set()).add((v, e))
        for vi, slots in votes.items():
            if len(slots) == 6:
                # choose one (v, e) per slot with distinct v covering V's terms
                for choice in itertools.product(*[sorted(slots[j]) for j in range(6)]):
                    vs = [c[0] for c in choice]
                    if len(set(vs)) == 6 and sorted(vs) == sorted(L[vi]['terms']):
                        lifts.append({'U': di, 'V': vi, 'pairs': [[d['terms'][j], vs[j], choice[j][1]] for j in range(6)]})
        if di % 200 == 0:
            say(f"  lift {di}/{len(L)}: {len(lifts)} lifts so far")
    say(f"lift candidates (mod P screen): {len(lifts)}")
    # exact verification of each lift at m + 1
    verified = []
    w1 = weights(m + 1)
    for lf in lifts:
        rows = []
        for (u, v, e) in lf['pairs']:
            cu = codes[u]; cv = codes[v]
            top = cu
            bot = np.where(cv != 0, ((cv - 1 + e) % 4) + 1, 0).astype(np.int8)
            rows.append(canon_codes(np.concatenate([top, bot])[None, :])[0])
        rows = np.array(rows)
        cs = exact_coefficients(rows, m + 1)
        if cs is not None:
            verified.append({'pairs': lf['pairs'], 'codes': [''.join('.1i-j'[c] for c in r) for r in rows], 'coeff': [str(c) for c in cs]})
    say(f"exactly verified six-term decompositions of sqrt(T)^{m+1}: {len(verified)}")
    json.dump({'m': m, 'lift_candidates': len(lifts), 'verified': verified, 'complete_list': dec['complete']},
              open(os.path.join(out, f'lifts_m{m+1}.json'), 'w'), indent=1)
    if verified:
        say(f"RESULT: chi(sqrtT^{m+1}) <= 6 (decomposition found)")
    elif dec['complete']:
        say(f"RESULT: no six-term decomposition of sqrt(T)^{m+1}: chi(sqrtT^{m+1}) >= 7")


