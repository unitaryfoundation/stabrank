def cmd_numeric(m, out, pivot):
    codes = load_codes(m, out)
    N, D = codes.shape
    tab = np.array([0, 1, 1j, -1, -1j])
    V = tab[codes]
    z = np.exp(1j * np.pi / 8); w = weights(m)
    B = np.stack([z ** (k * w) for k in (1, 5, 9, 13)], axis=1)
    Q, _ = np.linalg.qr(B)
    R = V - (V @ Q.conj()) @ Q.T
    ra = R[pivot]; ra = ra / np.linalg.norm(ra)
    Rp = R - np.outer(R @ ra.conj(), ra)
    nr = np.linalg.norm(Rp, axis=1)
    Za = np.flatnonzero(nr < 1e-8)
    keys = {}
    for i in np.flatnonzero(nr >= 1e-8):
        r = Rp[i]; p = int(np.flatnonzero(np.abs(r) > 0.1 * np.abs(r).max())[0]); r = r / r[p]
        keys.setdefault((p,) + tuple(np.round(r.view(np.float64), 5)), []).append(int(i))
    need = max(6 - len(Za), 1)
    cands = []
    for k, mem in keys.items():
        if len(mem) >= need:
            sel = np.array(sorted(mem + [int(i) for i in Za]))
            if np.linalg.matrix_rank(V[sel], tol=1e-8) >= 6:
                cands.append([int(i) for i in sel])
    print(json.dumps({'pivot': int(pivot), 'Z_a': [int(i) for i in Za], 'classes': len(keys), 'candidates': sorted(cands)}))


