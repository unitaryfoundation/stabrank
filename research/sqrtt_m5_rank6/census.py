"""Complete rank-6 census of sqrt(T)^{(x) m} (m = 5 on Perlmutter, m = 4 as a control) through the Galois-forced
subspace, its closure under the symmetry group, and the lift of every six-term decomposition to m + 1 qubits.

Why six terms are a plane census. Let V4 = span(t_1, t_5, t_9, t_13), with t_k = (1, zeta^k)^{(x) m}, which lies in
the span W of every stabilizer decomposition of t_1 = sqrt(2)^m sqrt(T)^{(x) m} (Galois descent, card S0601). Six
terms whose span contains V4 and which include no decomposition with fewer terms (chi = 6 at m = 5) are independent,
so dim W = 6 and the six residues modulo V4 span a two-dimensional space. Fix one term a of the decomposition. The
other five residues lie in span(r(a), r(b)) for any one of them b, so modulo V4 + span(a) the five are pairwise
parallel or zero. The census therefore pivots on a and groups every state by the projective class of its residue
modulo V4 + span(a) (exact modular arithmetic under two primes, keys as in census.py); every class C with
|C| + |Z_a| >= 6, where Z_a is the set of states whose residue is parallel to r(a) or zero (a itself among them), is
a candidate set S = C u Z_a. When S has exact rank 6 with V4 in its span (the case met in the run, checked exactly in
the collection stage), the six-term decompositions inside S are exactly its independent six-subsets, since any six
independent states of S span V4 + the plane, which contains t_1; otherwise every six-subset is decided exactly on
its own. The modular rank screen on candidate sets loses nothing: a 6 x 6 minor of a matrix with entries in {0, +-1,
+-i} has norm at most 6^6 = 46,656 < P, so exact rank at least 6 implies rank at least 6 modulo either prime,
and no class that could carry a decomposition is discarded.

Why orbit representatives suffice. The group G generated by the qubit permutations S_m and the diagonal Clifford
S^{(x) m} (amplitude at x multiplied by i^{|x|}) maps the set of six-term decompositions to itself: permutations fix
t_1 and V4; and if sum c_j s_j = t_1 then applying the automorphism zeta -> zeta^5 of Q(zeta), which fixes every
stabilizer state, gives sum sigma(c_j) s_j = t_5 = S^{(x) m} t_1, so {S^{+(x) m} s_j} is a decomposition. Every
decomposition contains a term, some g in G carries that term to its orbit representative a, and g carries the
decomposition to one containing a, which the pivot a finds. The closure of the representatives' decompositions
under G is then the complete list.

Soundness of the modular screen, as in census.py: if two residues modulo V4 + span(a) are parallel over Q(zeta),
r' = lambda r, then modulo P either lambda reduces to a nonzero scalar and the keys coincide, or one of them
vanishes mod P and lands in Z_a. Z_a is taken as the union over both primes, classes jointly under both primes.

    python census.py reps M OUT                   orbit representatives of the states under G
    python census.py run  M OUT [--workers W] [--pivots i,j,...] [--limit n]
    python census.py collect M OUT                exact decisions, decomposition list, closure under G
    python census.py lift M OUT                   lift of every decomposition to m + 1 by the slicing lemma
    python census.py numeric M OUT PIVOT          floating-point recomputation of one pivot (control)
"""
