DICT_CAP = {2: 5, 3: 3, 5: 2}     # largest n with an in-memory dictionary
_DICTS = {}


def dict_for(p, n):
    """The (p, n) dictionary, cached in memory and, when SECTORS_DICT_CACHE
    names a directory, on disk (the five-qubit dictionary takes 240 s to
    enumerate and 1.2 GB)."""
    if n < 1 or n > DICT_CAP.get(p, 0):
        return None
    if (p, n) not in _DICTS:
        t0 = time.time()
        cache = os.environ.get("SECTORS_DICT_CACHE")
        path = os.path.join(cache, f"dict_p{p}_n{n}.npy") if cache else None
        if path and os.path.exists(path):
            _DICTS[(p, n)] = np.load(path)
        else:
            _DICTS[(p, n)] = dictionary(p, n)
            if path:
                np.save(path, _DICTS[(p, n)])
        print(f"  [dictionary p={p} n={n}: {_DICTS[(p, n)].shape[1]} states, {time.time() - t0:.0f}s]", flush=True)
    return _DICTS[(p, n)]


# ---------------------------------------------------------------- Paulis ---

def omega(p):
    return np.exp(2j * np.pi / p)


def single_pauli(p, a, c):
    """X^a Z^c as a p x p matrix, X|x> = |x+1>, Z|x> = w^x |x>."""
    w = omega(p)
    X = np.roll(np.eye(p), a, axis=0)
    Z = np.diag(w ** (c * np.arange(p)))
    return X @ Z


def pauli_labels(p):
    return [(a, c) for a in range(p) for c in range(p) if (a, c) != (0, 0)]


def label_str(string):
    return " ".join(f"X^{a}Z^{c}" for a, c in string)


def parse_label(s):
    out = []
    for tok in s.split():
        a, c = tok.replace("X^", "").split("Z^")
        out.append((int(a), int(c)))
    return out


def apply_string(psi, p, m, string, power=1):
    """(x)_i (X^{a_i} Z^{c_i})^power applied to psi, as a vector op."""
    v = psi.reshape((p,) * m)
    w = omega(p)
    for i, (a, c) in enumerate(string):
        for _ in range(power):
            if c:
                shape = [1] * m
                shape[i] = p
                v = v * (w ** (c * np.arange(p))).reshape(shape)
            if a:
                v = np.roll(v, a, axis=i)
    return v.reshape(-1)


def string_scalar(p, string):
    """lambda with P^p = lambda I for P = (x) X^a Z^c."""
    lam = 1.0 + 0j
    for a, c in string:
        q = single_pauli(p, a, c)
        qp = np.linalg.matrix_power(q, p)
        lam *= qp[0, 0]
    return lam


def sector_vectors(psi, p, m, strings):
    """Joint eigensector projections of psi for the commuting strings, as a
    dict s -> vector (s a tuple of eigenvalue exponents)."""
    w = omega(p)
    parts = {(): psi}
    for P in strings:
        lam = string_scalar(p, P)
        root = lam ** (1.0 / p)
        nxt = {}
        for s, v in parts.items():
            powers = [v]
            cur = v
            for _ in range(p - 1):
                cur = apply_string(cur, p, m, P) / root
                powers.append(cur)
            for e in range(p):
                proj = sum(w ** (-e * j) * powers[j] for j in range(p)) / p
                nxt[s + (e,)] = proj
        parts = nxt
    return parts


def commute(p, P, Q):
    return sum(a1 * c2 - a2 * c1 for (a1, c1), (a2, c2) in zip(P, Q)) % p == 0


def independent(p, strings):
    """The strings generate a group of order p^k (no nontrivial relation mod phase)."""
    M = np.array([[x for ac in P for x in ac] for P in strings], dtype=np.int64) % p
    return rank_mod_p(M, p) == len(strings)


def rank_mod_p(M, p):
    M = M.copy() % p
    r = 0
    rows, cols = M.shape
    for c in range(cols):
        piv = next((i for i in range(r, rows) if M[i, c] % p), None)
        if piv is None:
            continue
        M[[r, piv]] = M[[piv, r]]
        M[r] = (M[r] * pow(int(M[r, c]), -1, p)) % p
        for i in range(rows):
            if i != r and M[i, c]:
                M[i] = (M[i] - M[i, c] * M[r]) % p
        r += 1
    return r


# ---------------------------------------------------- Clifford reduction ---

class Reducer:
    """A Clifford, as a gate list, mapping the generators to Z_0, ..., Z_{k-1}.

    Symplectic rules (a, c per site): F_i: (a, c) -> (-c, a); S_i^k: (a, c) ->
    (a, c + k a); M_{u, i}: (a, c) -> (u a, u^-1 c); SUM_{i -> j}: a_j += a_i,
    c_i -= c_j; SWAP. Each gate is applied to vectors as an index or phase
    operation; --control checks the rules against dense matrices.
    """

    def __init__(self, p, m):
        self.p, self.m, self.gates = p, m, []

    def build(self, strings):
        p, m = self.p, self.m
        cur = [[list(ac) for ac in P] for P in strings]

        def F(i):
            self.gates.append(("F", i))
            for P in cur:
                a, c = P[i]
                P[i] = [(-c) % p, a % p]

        def S(i, k):
            k %= p
            if k:
                self.gates.append(("S", i, k))
                for P in cur:
                    a, c = P[i]
                    P[i] = [a, (c + k * a) % p]

        def Mul(i, u):
            u %= p
            if u != 1:
                self.gates.append(("M", i, u))
                ui = pow(u, -1, p)
                for P in cur:
                    a, c = P[i]
                    P[i] = [(u * a) % p, (ui * c) % p]

        def SUM(i, j, times=1):
            times %= p
            for _ in range(times):
                self.gates.append(("SUM", i, j))
                for P in cur:
                    P[j][0] = (P[j][0] + P[i][0]) % p
                    P[i][1] = (P[i][1] - P[j][1]) % p

        def SWAP(i, j):
            if i != j:
                self.gates.append(("SWAP", i, j))
                for P in cur:
                    P[i], P[j] = P[j], P[i]

        for t in range(len(strings)):
            P = cur[t]
            for i in range(t):
                assert P[i][0] == 0, "generator does not commute with the reduced Z's"
            active = [i for i in range(t, m) if P[i] != [0, 0]]
            assert active, "dependent generator"
            for i in active:
                if P[i][0] == 0:
                    F(i)
                a, c = P[i]
                S(i, (-c * pow(a, -1, p)) % p)
                Mul(i, pow(P[i][0], -1, p))
            i0 = active[0]
            for i in active[1:]:
                SUM(i0, i, p - 1)           # SUM^{-1}: X_i0 X_i -> X_i0
            F(i0)                            # X_i0 -> Z_i0
            for i in range(t):
                SUM(i, i0, P[i][1])          # remove Z_i^{c} from Z_i^c Z_i0
            SWAP(t, i0)
            assert all(cur[t][i] == [0, 0] for i in range(m) if i != t) and cur[t][t] == [0, 1], cur[t]
        return self

    def apply(self, psi):
        p, m = self.p, self.m
        v = psi.reshape((p,) * m)
        w = omega(p)
        Fm = np.array([[w ** (x * y) for x in range(p)] for y in range(p)]) / np.sqrt(p)
        for g in self.gates:
            if g[0] == "F":
                i = g[1]
                v = np.moveaxis(np.tensordot(Fm, v, axes=([1], [i])), 0, i)
            elif g[0] == "S":
                _, i, k = g
                if p == 2:
                    ph = np.array([1, 1j]) ** k
                else:
                    ph = w ** ((k * np.arange(p) * (np.arange(p) - 1) // 2) % p)
                shape = [1] * m
                shape[i] = p
                v = v * ph.reshape(shape)
            elif g[0] == "M":
                _, i, u = g
                ui = pow(u, -1, p)
                idx = (ui * np.arange(p)) % p          # new(y) = old(u^-1 y)
                v = np.take(v, idx, axis=i)
            elif g[0] == "SUM":
                _, i, j = g
                out = np.empty_like(v)
                for xi in range(p):
                    sl = [slice(None)] * m
                    sl[i] = xi
                    sl = tuple(sl)
                    out[sl] = np.roll(v[sl], xi, axis=j if j < i else j - 1)
                v = out
            elif g[0] == "SWAP":
                v = np.swapaxes(v, g[1], g[2])
        return v.reshape(-1)

    def dense(self):
        """The Clifford as a dense unitary (controls only)."""
        p, m = self.p, self.m
        dim = p ** m
        U = np.eye(dim, dtype=complex)
        for col in range(dim):
            U[:, col] = self.apply(np.eye(dim, dtype=complex)[:, col])
        return U


def reduce_sectors(psi, p, m, strings):
    """[(s, weight, u_s or None)] with u_s the normalized (m-k)-qudit state."""
    k = len(strings)
    secs = sector_vectors(psi, p, m, strings)
    red = Reducer(p, m).build(strings)
    out = []
    for s, v in sorted(secs.items()):
        nrm = np.linalg.norm(v)
        if nrm < 1e-10:
            out.append((s, 0.0, None))
            continue
        wv = red.apply(v).reshape(p ** k, -1)
        blocks = np.linalg.norm(wv, axis=1)
        b = int(np.argmax(blocks))
        if not np.allclose(np.delete(blocks, b), 0, atol=1e-8):
            raise AssertionError("the Clifford reduction did not isolate one block")
        out.append((s, float(nrm ** 2), wv[b] / blocks[b]))
    return out


# ----------------------------------------------------------- rank tests ---

def is_stab(u, p, n):
    try:
        term_from_vector(u, p, n)
        return True
    except (NotStabilizer, ValueError, IndexError):
        return False


def sector_rank(u, p, n, rank3=False, D=None):
    """0, 1, 2, 3, or the strings '>3' (dictionary, rank3 failed) / '>=3'
    (dictionary, rank3 not run) / '>=2' (no dictionary)."""
    if u is None:
        return 0
    if n == 0:
        return 1
    if is_stab(u, p, n):
        return 1
    if D is None:
        return ">=2"
    r2, _ = rank2_search(u, D)
    if r2 == "RANK1":
        return 1
    if r2:
        return 2
    if not rank3:
        return ">=3"
    r = rank3_search(u, D, workers=1)
    return 3 if r["found"] else ">3"


def rank_value(r):
    return {">=2": 2, ">=3": 3, ">3": 4}.get(r, r)


ANNEAL_CFG = {"seeds": 1, "chains": 4, "iters": 2000, "cooling": 0.99}


def anneal(u, p, n, rank):
    """Best of ANNEAL_CFG['seeds'] annealing runs at fixed rank on the sector
    state u (n qudits); returns (residual, seconds, term vectors)."""
    from stabrank import generate_random_stabilizer_state
    from stabrank.stabrank_core import run_sa_pauli_expansion
    t0 = time.time()
    best = None
    for seed in range(1, ANNEAL_CFG["seeds"] + 1):
        np.random.seed(seed)
        basis = [generate_random_stabilizer_state(n, p=p) for _ in range(rank)]
        _, funcs, _, err, _, _ = run_sa_pauli_expansion(
            target=u, n_orig=n, p_prime=p, k_subset_size=rank, initial_basis=basis,
            initial_temperature=1.0, cooling_rate=ANNEAL_CFG["cooling"],
            num_iterations_at_temp=ANNEAL_CFG["iters"],
            min_temperature=1 / 4000, atol=1e-7, two_func_perturb_prob=0.3,
            random_replace_prob=0.05, use_real_qubit_moves=False, clifford_ratio=0.5,
            early_exit_threshold=1e-9, seed=seed, num_chains=ANNEAL_CFG["chains"])
        if best is None or err < best[0]:
            best = (float(err), [np.asarray(f, dtype=complex) for f in funcs])
        if err < 1e-9:
            break
    return best[0], time.time() - t0, best[1]


