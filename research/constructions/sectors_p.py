def local_orbits(orbit, p):
    """Orbits of the nonidentity single-qudit Paulis under the local Clifford
    stabilizer of |M>, as (reps, order, class_of)."""
    a1 = alpha(orbit)
    G = clifford_group(p)
    stab = [U for U in G if abs(abs(np.vdot(a1, U @ a1)) - 1) < 1e-9]
    labels = pauli_labels(p)

    def key(Pm):
        v = Pm.ravel()
        v = v / v[np.flatnonzero(np.abs(v) > 1e-9)[0]]
        return (np.round(v, 6) + 0.0).tobytes()

    index = {key(single_pauli(p, a, c)): (a, c) for a, c in labels}
    parent = {pc: pc for pc in labels}

    def find(x):
        while parent[x] != x:
            x = parent[x]
        return x

    perms = []
    for U in stab:
        perm = {(0, 0): (0, 0)}
        for a, c in labels:
            img = index[key(U @ single_pauli(p, a, c) @ U.conj().T)]
            perm[(a, c)] = img
            ra, rb = find((a, c)), find(img)
            if ra != rb:
                parent[ra] = rb
        perms.append(perm)
    reps = sorted({find(pc) for pc in labels})
    return reps, len(stab), {pc: find(pc) for pc in labels}, perms


def gl2(p):
    return [(a, b, c, d) for a in range(p) for b in range(p) for c in range(p) for d in range(p)
            if (a * d - b * c) % p]


def canonical_pair(p, P1, P2, perms, G2=None):
    """Canonical form of the group <P1, P2> under the local stabilizer on each
    copy, the copy permutations, and the change of generators (GL_2(F_p))."""
    G2 = G2 or gl2(p)
    best = None
    for a, b, c, d in G2:
        sites = []
        for (a1, c1), (a2, c2) in zip(P1, P2):
            q1 = ((a * a1 + b * a2) % p, (a * c1 + b * c2) % p)
            q2 = ((c * a1 + d * a2) % p, (c * c1 + d * c2) % p)
            sites.append(min((perm[q1], perm[q2]) for perm in perms))
        key = tuple(sorted(sites))
        if best is None or key < best:
            best = key
    return best


def k1_classes(orbit, p, m):
    reps, order, _, _ = local_orbits(orbit, p)
    return [list(c) for c in itertools.combinations_with_replacement(reps, m)], order, reps


def expectation_table(orbit, p):
    """e[(a, c)][j] = <M| (X^a Z^c)^j |M> and the scalar of (X^a Z^c)^p."""
    a1 = alpha(orbit)
    e, lam = {}, {}
    for a, c in pauli_labels(p):
        q = single_pauli(p, a, c)
        pw = np.eye(p, dtype=complex)
        vals = []
        for _ in range(p):
            vals.append(np.vdot(a1, pw @ a1))
            pw = pw @ q
        e[(a, c)] = np.array(vals)
        lam[(a, c)] = pw[0, 0]
    return e, lam


_SITE_TABLES = {}


def site_tables(orbit, p):
    """t[q1, q2, j, l] = <M| q1^j q2^l |M> over the nonidentity Paulis, and the
    scalars lam[q] with q^p = lam I."""
    if (orbit, p) in _SITE_TABLES:
        return _SITE_TABLES[(orbit, p)]
    a1 = alpha(orbit)
    labels = pauli_labels(p)
    L = len(labels)
    mats = {q: single_pauli(p, *q) for q in labels}
    powers = {q: [np.linalg.matrix_power(mats[q], j) for j in range(p)] for q in labels}
    lam = np.array([np.linalg.matrix_power(mats[q], p)[0, 0] for q in labels])
    t = np.zeros((L, L, p, p), dtype=complex)
    for i1, q1 in enumerate(labels):
        for i2, q2 in enumerate(labels):
            for j in range(p):
                for l in range(p):
                    t[i1, i2, j, l] = np.vdot(a1, powers[q1][j] @ powers[q2][l] @ a1)
    _SITE_TABLES[(orbit, p)] = (t, lam)
    return t, lam


def pair_weights_batch(orbit, p, m, P1, strings2=None, S2=None):
    """Number of nonvanishing joint sectors for (P1, P2) over a batch of P2,
    given as label tuples (strings2) or as label-index arrays S2 (B, m).

    <psi| P1^j P2^l |psi> = prod_i <M| q1_i^j q2_i^l |M> up to the rescaling
    of P1 and P2 to order p; the weights are its Fourier transform."""
    w = omega(p)
    labels = pauli_labels(p)
    idx = {q: i for i, q in enumerate(labels)}
    t, lam = site_tables(orbit, p)
    if S2 is None:
        S2 = np.array([[idx[q] for q in P2] for P2 in strings2])
    i1s = np.array([idx[tuple(q)] for q in P1])
    lam1 = np.prod(lam[i1s]) ** (1.0 / p)
    lam2 = np.prod(lam[S2], axis=1) ** (1.0 / p)                       # (B,)
    E = np.ones((S2.shape[0], p, p), dtype=complex)
    for i in range(m):
        E *= t[i1s[i], S2[:, i]]                                        # (B, p, p)
    j = np.arange(p)
    E *= (lam1 ** (-j))[None, :, None] * (lam2[:, None, None] ** (-j)[None, None, :])
    Fm = np.array([[w ** (-s * jj) for jj in range(p)] for s in range(p)]) / p
    W = np.einsum("sj,bjl,tl->bst", Fm, E, Fm)                         # weights (B, p, p)
    W = np.abs(W)
    return (W > 1e-9).sum(axis=(1, 2)), W


def partners(p, m, P1, S_all, A):
    """Indices into S_all of the strings commuting with P1 and independent of it."""
    P1a = np.array(P1)                                                  # (m, 2)
    a2, c2 = A[S_all][:, :, 0], A[S_all][:, :, 1]                       # (N, m)
    symp = (P1a[:, 0][None, :] * c2 - a2 * P1a[:, 1][None, :]).sum(axis=1) % p
    ok = symp == 0
    for jmul in range(1, p):
        mult = (jmul * P1a) % p
        ok &= ~np.all((a2 == mult[:, 0][None, :]) & (c2 == mult[:, 1][None, :]), axis=1)
    return np.flatnonzero(ok)


def group_key(p, strings):
    """The set of group elements mod phase, as a frozenset of tuples."""
    k = len(strings)
    elems = set()
    for coeffs in itertools.product(range(p), repeat=k):
        v = [0] * (2 * len(strings[0]))
        for cf, P in zip(coeffs, strings):
            for i, (a, c) in enumerate(P):
                v[2 * i] = (v[2 * i] + cf * a) % p
                v[2 * i + 1] = (v[2 * i + 1] + cf * c) % p
        elems.add(tuple(v))
    return frozenset(elems)


# ------------------------------------------------------------------ main ---

ANNEAL_HITS = []


def analyse(orbit, p, m, strings, rank3, D, anneal_rank=None, verbose=True, anneal_sectors=None):
    psi = target(orbit, m)
    n = m - len(strings)
    secs = reduce_sectors(psi, p, m, strings)
    ranks, weights = [], []
    annealed = 0
    for s, wgt, u in secs:
        r = sector_rank(u, p, n, rank3=rank3, D=D)
        if anneal_rank and r in (">=2", ">=3") and u is not None and (anneal_sectors is None or annealed < anneal_sectors):
            annealed += 1
            err, secs_, vecs = anneal(u, p, n, anneal_rank)
            if err > 1e-9:
                r = f"anneal r={anneal_rank} residual {err:.4f} ({secs_:.0f}s)"
            else:
                r = f"<={anneal_rank} (annealed, {secs_:.0f}s)"
                ANNEAL_HITS.append((strings, s, u, vecs))
        ranks.append(r)
        weights.append(round(wgt, 4))

    def val(r):
        if isinstance(r, str) and r.startswith("<="):
            return anneal_rank
        if isinstance(r, str) and r.startswith("anneal"):
            return 2
        return rank_value(r)

    total = sum(val(r) for r in ranks)
    if verbose:
        print(f"  {' | '.join(label_str(P) for P in strings)}: weights {weights}, ranks {ranks}, "
              f"total >= {total}", flush=True)
    return ranks, weights, total


def save_hits(path):
    if not path or not ANNEAL_HITS:
        return
    np.savez(path, **{f"hit{i}_sector": np.array([str(strings), str(s)]) for i, (strings, s, u, vecs) in enumerate(ANNEAL_HITS)},
             **{f"hit{i}_target": u for i, (strings, s, u, vecs) in enumerate(ANNEAL_HITS)},
             **{f"hit{i}_terms": np.array(vecs) for i, (strings, s, u, vecs) in enumerate(ANNEAL_HITS)})
    print(f"saved {len(ANNEAL_HITS)} annealed sector decompositions to {path}")


def control(argv_orbit=None):
    """Dense checks of the symplectic rules, and the known sector results."""
    rng = np.random.default_rng(3)
    for p, m in [(2, 3), (3, 3), (5, 2), (3, 4)]:
        for _ in range(6):
            k = 1 if p == 5 or m < 3 else 2
            while True:
                strings = [[tuple(int(x) for x in rng.integers(0, p, 2)) for _ in range(m)] for _ in range(k)]
                if all(any(ac != (0, 0) for ac in P) for P in strings) and \
                   all(commute(p, strings[i], strings[j]) for i in range(k) for j in range(i + 1, k)) and \
                   independent(p, strings):
                    break
            red = Reducer(p, m).build(strings)
            U = red.dense()
            assert np.allclose(U.conj().T @ U, np.eye(p ** m), atol=1e-9), "not unitary"
            for t, P in enumerate(strings):
                Pd = np.array([[1.0 + 0j]])
                for a, c in P:
                    Pd = np.kron(Pd, single_pauli(p, a, c))
                Zt = np.array([[1.0 + 0j]])
                for i in range(m):
                    Zt = np.kron(Zt, single_pauli(p, 0, 1) if i == t else np.eye(p))
                Q = U @ Pd @ U.conj().T
                ratio = Q[np.abs(Zt) > 0.5] / Zt[np.abs(Zt) > 0.5]
                assert np.allclose(ratio, ratio[0], atol=1e-8) and np.allclose(np.abs(Q - ratio[0] * Zt), 0, atol=1e-8), \
                    f"reduction failed at p={p} m={m} {strings}"
    print("Clifford reduction: dense checks pass (p = 2, 3, 5)")
    # T5 m=2, Z Z: all five sectors stabilizer states
    r, _, tot = analyse("T5", 5, 2, [[(0, 1), (0, 1)]], False, dict_for(5, 1))
    assert r == [1] * 5 and tot == 5, r
    print("T5 m=2 Z Z: five stabilizer sectors, total 5 (chi(T5^2) = 5)")
    # T3 m=3, Z Z Z: three sectors of rank 3 (exhaustive fact behind T3-m5-upper-18)
    r, _, tot = analyse("T3", 3, 3, [[(0, 1)] * 3], True, dict_for(3, 2))
    assert r == [3, 3, 3], r
    print("T3 m=3 Z Z Z: sector ranks 3, 3, 3")
    # N m=3, X^2 X^2 X^2 has one rank-2 sector (sectors.py, 2026-09-20)
    r, _, tot = analyse("N", 3, 3, [[(2, 0)] * 3], True, dict_for(3, 2))
    assert sorted(rank_value(x) for x in r)[0] == 2, r
    print("N m=3 X^2 X^2 X^2: one rank-2 sector")
    # weight formula against explicit projections
    for orbit, p, m in [("T5", 5, 2), ("N", 3, 3), ("qubit_H", 2, 4), ("S", 3, 4)]:
        labels = pauli_labels(p)
        psi = target(orbit, m)
        for _ in range(5):
            while True:
                P1 = [labels[int(i)] for i in rng.integers(0, len(labels), m)]
                P2 = [labels[int(i)] for i in rng.integers(0, len(labels), m)]
                if commute(p, P1, P2) and independent(p, [P1, P2]):
                    break
            cnt, W = pair_weights_batch(orbit, p, m, P1, [P2])
            secs = sector_vectors(psi, p, m, [P1, P2])
            direct = sorted(np.linalg.norm(v) ** 2 for v in secs.values())
            assert np.allclose(sorted(W[0].ravel()), direct, atol=1e-8), (orbit, P1, P2)
    print("sector weights: Fourier formula matches explicit projections")
    return 0


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("orbit", nargs="?")
    ap.add_argument("m", nargs="?", type=int)
    ap.add_argument("--k", type=int, default=1)
    ap.add_argument("--rank3", action="store_true")
    ap.add_argument("--anneal", type=int, default=None, help="anneal undecided sectors at this rank")
    ap.add_argument("--bound", type=int, default=None,
                    help="current upper bound of the cell; k = 2 pairs with at least this many "
                         "nonvanishing sectors are skipped")
    ap.add_argument("--only", default=None, help="one string (k = 1) or 'P1 | P2' (k = 2) to analyse")
    ap.add_argument("--control", action="store_true")
    ap.add_argument("--max-pairs", type=int, default=100000, help="rank analysis on at most this many pair classes")
    ap.add_argument("--anneal-sectors", type=int, default=None, help="anneal at most this many sectors per group")
    ap.add_argument("--skip", type=int, default=0, help="skip the first N pair classes (resume a killed run)")
    ap.add_argument("--anneal-seeds", type=int, default=1)
    ap.add_argument("--anneal-chains", type=int, default=4)
    ap.add_argument("--anneal-iters", type=int, default=2000)
    ap.add_argument("--anneal-cooling", type=float, default=0.99)
    ap.add_argument("--save-hits", default=None, help="write annealed sector decompositions here (npz)")
    a = ap.parse_args(argv[1:])
    if a.control:
        return control()
    ANNEAL_CFG.update(seeds=a.anneal_seeds, chains=a.anneal_chains, iters=a.anneal_iters,
                      cooling=a.anneal_cooling)
    orbit, m = a.orbit, a.m
    p = ORBIT_P[orbit]
    t0 = time.time()
    if a.only:
        strings = [parse_label(s) for s in a.only.split("|")]
        D = dict_for(p, m - len(strings))
        analyse(orbit, p, m, strings, a.rank3, D, anneal_rank=a.anneal, anneal_sectors=a.anneal_sectors)
        save_hits(a.save_hits)
        return 0
    classes, order, reps = k1_classes(orbit, p, m)
    print(f"{orbit} m={m} p={p}: local stabilizer of order {order}, {len(reps)} orbits of nonidentity "
          f"Paulis {reps}, {len(classes)} single-string classes with full support")
    if a.k == 1:
        D = dict_for(p, m - 1)
        best = None
        for cls in classes:
            ranks, weights, total = analyse(orbit, p, m, [cls], a.rank3, D, anneal_rank=a.anneal,
                                            anneal_sectors=a.anneal_sectors)
            if best is None or total < best[0]:
                best = (total, cls, ranks)
        print(f"smallest sector-rank total {best[0]} at {label_str(best[1])} {best[2]} [{time.time() - t0:.0f}s]")
        save_hits(a.save_hits)
        return 0
    # k = 2: screen every (P1 rep, P2) by nonvanishing-sector count
    labels = pauli_labels(p)
    A = np.array(labels)
    S_all = np.array(list(itertools.product(range(len(labels)), repeat=m)), dtype=np.int64)
    bound = a.bound if a.bound is not None else p ** 2 + 1
    print(f"k=2: {len(classes)} P1 classes x {len(S_all)} P2 strings; keeping pairs with fewer than "
          f"{bound} nonvanishing sectors")
    seen_groups = set()
    kept = []
    hist = {}
    _, _, _, perms = local_orbits(orbit, p)
    G2 = gl2(p)
    for cls in classes:
        P1 = [tuple(x) for x in cls]
        cand = partners(p, m, P1, S_all, A)
        for start in range(0, len(cand), 20000):
            S2 = S_all[cand[start:start + 20000]]
            cnt, W = pair_weights_batch(orbit, p, m, P1, S2=S2)
            vals, counts = np.unique(cnt, return_counts=True)
            for v, c in zip(vals, counts):
                hist[int(v)] = hist.get(int(v), 0) + int(c)
            for row in np.flatnonzero(cnt < bound):
                P2 = [labels[i] for i in S2[row]]
                gk = canonical_pair(p, P1, P2, perms, G2)
                if gk in seen_groups:
                    continue
                seen_groups.add(gk)
                kept.append((int(cnt[row]), P1, P2))
    print(f"nonvanishing-sector histogram over all commuting independent pairs: {dict(sorted(hist.items()))} "
          f"[{time.time() - t0:.0f}s]")
    print(f"{len(kept)} pair classes (up to the local stabilizer, copy permutations, and change of "
          f"generators) with fewer than {bound} nonvanishing sectors")
    kept.sort(key=lambda t: t[0])
    D = dict_for(p, m - 2) if kept else None
    best = None
    for c, P1, P2 in kept[a.skip: a.skip + a.max_pairs]:
        ranks, weights, total = analyse(orbit, p, m, [P1, P2], a.rank3, D, anneal_rank=a.anneal,
                                        anneal_sectors=a.anneal_sectors)
        if best is None or total < best[0]:
            best = (total, P1, P2, ranks)
    if best:
        print(f"smallest sector-rank total {best[0]} at {label_str(best[1])} | {label_str(best[2])} {best[3]} "
              f"[{time.time() - t0:.0f}s]")
    return 0


