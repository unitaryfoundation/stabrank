"""Pauli-group eigensector decompositions of |M>^m for every prime on the board.

Generalizes sectors.py (qutrits, one Pauli string) to p in {2, 3, 5} and to
groups generated by k commuting Pauli strings. For an abelian group G of
Pauli strings with p^k elements and full support on the m copies (every copy
carries a nonidentity element of G), |M>^m = sum_s Pi_s |M>^m over the p^k
joint eigensectors s, so chi(|M>^m) <= sum_s chi(Pi_s |M>^m). A sector lives
in the stabilizer code {P_i = w^{s_i}}, and a Clifford C with C P_i C^-1 = Z_i
turns it into |s> (x) u_s with u_s an (m-k)-qudit state whose stabilizer rank
is the sector's rank (any decomposition of the sector projects into the code
term by term). The rank of u_s is decided exactly in the (m-k)-qudit
dictionary when that dictionary fits (five qubits, three qutrits, two
ququints): 1 if u_s is a stabilizer state, 2 by rank2_search, 3 by
rank3_search with --rank3, else "> 3". Without a dictionary the script
reports 0, 1, or ">= 2" and, with --anneal R, runs a short annealing search
for a rank-R decomposition of u_s.

The 2026-09-24 identity chi(|T5>^2) = 5 is the case p = 5, m = 2, G = <Z Z>:
every sector is a stabilizer state. This script finds it in under a second
(`sectors_p.py T5 2`), which is the control.

Enumeration. For k = 1 the strings are taken up to the local Clifford
stabilizer of |M> on each copy and the copy permutations, as in sectors.py.
For k = 2 the pairs (P1, P2) with P1 a k = 1 representative and P2 any
string are screened first by the sector weights, which are cheap: the weight
of sector s is the Fourier transform over G of the expectation values
<psi|g|psi> = prod_i <M|g_i|M>. Only pairs whose number of nonvanishing
sectors is below the cell's current upper bound go to the rank analysis,
since every nonvanishing sector costs at least one term. Pairs are deduped
by the group they generate.

Usage:
    sectors_p.py ORBIT M [--k 1|2] [--rank3] [--anneal R] [--bound B]
                 [--only "X^aZ^c X^aZ^c ..."] [--control]
"""

